function normalize(name: string) {
  return name
    .trim()
    .replace(/^phosphor:/i, "")
    .replace(/^lucide:/i, "")
    .replace(/^icon:\s*/i, "")
    .replace(/[\s_-]+/g, "")
    .toLowerCase();
}

export function hasIcon(name: string): boolean {
  if (!name || typeof name !== "string") return false;
  const key = normalize(name);
  return Boolean(ICONS[key]);
}

export function AppIcon({
  name,
  size = 20,
  color = "currentColor",
  strokeWidth = 2,
  className,
  "aria-hidden": ariaHidden = true,
  ...props
}: {
  name: string;
  size?: number;
  color?: string;
  className?: string;
} & Omit<LucideProps, "size" | "color" | "ref">) {
  const Icon = ICONS[normalize(name)] ?? Sparkles;
  return (
    <Icon
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden={ariaHidden}
      {...props}
    />
  );
}

/** Soft branded stand-in for missing illustrations / hero art. */
export function MediaPlaceholder({
  label = "Image",
  height = 160,
  className = "",
}: {
  label?: string;
  height?: number | string;
  className?: string;
}) {
  return (
    <div
      className={`media-placeholder ${className}`}
      style={{ minHeight: height }}
      role="img"
      aria-label={label}
    >
      <AppIcon name="image" size={28} color="var(--lavender-purple)" />
      <span>{label}</span>
    </div>
  );
}
