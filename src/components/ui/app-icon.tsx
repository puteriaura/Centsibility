function normalize(name: string) {
  return name
    .trim()
     .replace(/^[a-z]+:/i, "")
    .replace(/^icon:\s*/i, "")
    .replace(/[\s_-]+/g, "")
    .toLowerCase();
}

export function hasIcon(name: string): boolean {
  if (!name || typeof name !== "string") return false;
  const key = normalize(name);
  return key === "penny" || Boolean(ICONS[key]);
}

export function AppIcon({
  name,
  size = 20,
  color = "currentColor",
  strokeWidth = 1.5,
  className,
  "aria-hidden": ariaHidden = true,
  ...props
}: {
  name: string;
  size?: number;
  color?: string;
  className?: string;
} & Omit<SVGProps<SVGSVGElement>, "size" | "color" | "ref" | "strokeWidth"> & { strokeWidth?: number }) {
  // Unknown names render a plain dot, so a missing mapping is visible rather than decorative
  if (normalize(name) === "penny") {
    return (
      <PennyFace
        size={size}
        className={className}
        aria-hidden={ariaHidden}
        {...props}
      />
    );
  }
  const icon = ICONS[normalize(name)] ?? CircleIcon;
  return (
    <HugeiconsIcon
      icon={icon}
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden={ariaHidden}
      {...props}
    />
  );
}

/** Soft branded stand-in for missing illustrations / hero art. */
export function MediaPlaceholder({
  label = "Image",
  height = 160,
  className = "",
}: {
  label?: string;
  height?: number | string;
  className?: string;
}) {
  return (
    <div
      className={`media-placeholder ${className}`}
      style={{ minHeight: height }}
      role="img"
      aria-label={label}
    >
      <AppIcon name="image" size={28} color="var(--lavender-purple)" />
      <span>{label}</span>
    </div>
  );
}
