import { createFileRoute } from "@tanstack/react-router";
import { useCallback, useEffect, useRef, useState } from "react";
import { useParentData } from "@/hooks/use-parent-data";
import { edgeParentGetStatement } from "@/lib/edge";
import { Skeleton } from "@/components/ui/skeleton";
import { format, startOfMonth, endOfMonth } from "date-fns";
import { toast } from "sonner";
import { PieChart, Pie, Cell, Tooltip as RechartsTooltip, ResponsiveContainer } from "recharts";
import { isDebitTransaction, isWalletTransaction, TRANSACTION_TYPE_LABELS } from "@/lib/finance";
import type { StatementResult, StatementTx as Tx } from "@/types/domain";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { SectionTitle } from "@/components/ui/section-title";
import { AppIcon } from "@/components/ui/app-icon";
import { formatRM } from "@/lib/format";
import { ParentLoadError } from "@/features/parent/components/ParentLoadError";

export const Route = createFileRoute("/parent/reports")({
  head: () => ({ meta: [{ title: "Monthly Statement — Centsibility" }] }),
  component: Reports,
});

const isDebit = isDebitTransaction;
const TYPE_LABELS = TRANSACTION_TYPE_LABELS;

function fmtRM(n: number) {
  return `${formatRM(Math.abs(n))}`;
}

function groupByDate(txs: Tx[]): Record<string, Tx[]> {
  return txs.reduce(
    (acc, tx) => {
      const d = tx.created_at.slice(0, 10);
      (acc[d] = acc[d] || []).push(tx);
      return acc;
    },
    {} as Record<string, Tx[]>,
  );
}

const PIE_COLORS = ["#EC008C", "#B60081", "#161A50", "#F5A623", "#17A673", "#9B72CF"];

function Reports() {
  const { kids, loans, loading, error, hasLoaded, lastLoadedAt, refresh } = useParentData();
  const [kidId, setKidId] = useState<string>("");
  const [month, setMonth] = useState<Date>(startOfMonth(new Date()));
  const [typeFilter, setTypeFilter] = useState<string>("ALL");
  const [stmt, setStmt] = useState<StatementResult>(null);
  const [fetching, setFetching] = useState(false);
  const [stmtError, setStmtError] = useState<string | null>(null);
  const stmtRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (kids.length && !kidId) setKidId(kids[0].id);
  }, [kids, kidId]);

  const fetchStatement = useCallback(async () => {
    if (!kidId) return;
    setFetching(true);
    setStmtError(null);
    try {
      const res = await edgeParentGetStatement({
        kidId,
        from: format(startOfMonth(month), "yyyy-MM-dd"),
        to: format(endOfMonth(month), "yyyy-MM-dd"),
      });
      setStmt(res);
      setStmtError(null);
    } catch (e: unknown) {
      const msg = e instanceof Error ? e.message : "Failed to load statement";
      setStmtError(msg);
      toast.error(msg);
    } finally {
      setFetching(false);
    }
  }, [kidId, month]);

  useEffect(() => {
    fetchStatement();
  }, [fetchStatement]);

  const handleDownloadPdf = () => {
    setTimeout(() => {
      window.print();
    }, 100);
  };

  const handleWhatsApp = () => {
    if (!stmt) return;
    const text = [
      `📄 *Monthly Statement – ${stmt.kid.name}*`,
      `Period: ${format(startOfMonth(month), "d MMM")} – ${format(endOfMonth(month), "d MMM yyyy")}`,
      `Total In : ${fmtRM(totalIn)}`,
      `Total Out: ${fmtRM(totalOut)}`,
      `Net      : ${net >= 0 ? "+" : ""}${fmtRM(net)}`,
      `Balance  : ${fmtRM(stmt.kid.balance)}`,
      `\nGenerated by Centsibility`,
    ].join("\n");
    window.open(`https://wa.me/?text=${encodeURIComponent(text)}`, "_blank");
  };

  const handleEmail = () => {
    if (!stmt) return;
    const subject = `Monthly Statement – ${stmt.kid.name} – ${format(month, "MMMM yyyy")}`;
    const body = [
      `Monthly Statement for ${stmt.kid.name}`,
      `Period: ${format(startOfMonth(month), "d MMM yyyy")} – ${format(endOfMonth(month), "d MMM yyyy")}`,
      ``,
      `Total Deposits : ${fmtRM(totalIn)}`,
      `Total Debits   : ${fmtRM(totalOut)}`,
      `Net Change     : ${net >= 0 ? "+" : ""}${fmtRM(net)}`,
      `Current Balance: ${fmtRM(stmt.kid.balance)}`,
      ``,
      `Generated by Centsibility`,
    ].join("\n");
    window.open(`mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`);
  };

  if (loading && !hasLoaded && !error) {
    return (
      <div className="space-y-4">
        <Skeleton style={{ height: "4rem", borderRadius: "16px" }} />
        <Skeleton style={{ height: "14rem", borderRadius: "20px" }} />
        <Skeleton style={{ height: "14rem", borderRadius: "20px" }} />
      </div>
    );
  }

  if (error && !hasLoaded) {
    return (
      <div className="space-y-6 pb-12">
        <ParentLoadError variant="page" onRetry={refresh} message={error} />
      </div>
    );
  }

  const stmtTxs: Tx[] = (stmt?.transactions ?? []).filter((t) => isWalletTransaction(t.type));
  const filtered = typeFilter === "ALL" ? stmtTxs : stmtTxs.filter((t) => t.type === typeFilter);
  const totalIn = stmtTxs.filter((t) => !isDebit(t.type, t.label)).reduce((s, t) => s + t.amount, 0);
  const totalOut = stmtTxs.filter((t) => isDebit(t.type, t.label)).reduce((s, t) => s + t.amount, 0);
  const net = totalIn - totalOut;

  const endBalance = stmt?.kid.balance ?? 0;
  let runningBalance = endBalance;
  const balanceMap = new Map<string, number>();
  for (let i = 0; i < stmtTxs.length; i++) {
    const tx = stmtTxs[i];
    balanceMap.set(tx.id, runningBalance);
    if (isDebit(tx.type, tx.label)) runningBalance += tx.amount;
    else runningBalance -= tx.amount;
  }

  const grouped = groupByDate(filtered);
  const sortedDates = Object.keys(grouped).sort((a, b) => b.localeCompare(a));
  const availableTypes = ["ALL", ...Array.from(new Set(stmtTxs.map((t) => t.type)))];
  const loanFees = stmtTxs.filter(
    (t) =>
      t.type === "FEE" ||
      (t.type === "WITHDRAWAL" && (t.label?.includes("fee") || t.label?.includes("Fee"))),
  );
  const overdue = loans.filter((l) => l.status === "active" && new Date(l.due_date) < new Date());

  return (
    <div className="space-y-6 pb-12">
      {error && hasLoaded && (
        <ParentLoadError variant="banner" onRetry={refresh} lastLoadedAt={lastLoadedAt} />
      )}
      {/* Header + Selector Controls */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-[var(--ink)] flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-xl bg-[var(--surface-pink)] text-[var(--primary-text)] flex items-center justify-center shrink-0">
              <AppIcon name="chart" size={20} />
            </div>
            Monthly Statements
          </h1>
          <p className="text-xs sm:text-sm text-[var(--text-secondary)] mt-0.5">
            Financial analytics, category breakdown, and exportable statements for your family.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <select
            value={kidId}
            onChange={(e) => setKidId(e.target.value)}
            className="h-10 px-3 text-xs sm:text-sm bg-white border border-[var(--border)] rounded-xl font-semibold text-[var(--ink)] outline-none focus:border-[var(--primary)]"
          >
            <option value="">Select Child</option>
            {kids.map((k) => (
              <option key={k.id} value={k.id}>
                {k.name}
              </option>
            ))}
          </select>

          <input
            type="month"
            value={format(month, "yyyy-MM")}
            onChange={(e) => {
              if (e.target.value) setMonth(startOfMonth(new Date(e.target.value + "-01")));
            }}
            className="h-10 px-3 text-xs sm:text-sm bg-white border border-[var(--border)] rounded-xl font-semibold text-[var(--ink)] outline-none focus:border-[var(--primary)]"
          />
        </div>
      </div>

      {fetching ? (
        <div className="space-y-3">
          <Skeleton style={{ height: "6rem", borderRadius: "16px" }} />
          <Skeleton style={{ height: "12rem", borderRadius: "16px" }} />
        </div>
      ) : stmtError ? (
        <Card variant="soft" className="p-8 text-center space-y-3">
          <div className="w-12 h-12 rounded-full flex items-center justify-center bg-[var(--error-soft)] border border-[var(--error)]/30 mx-auto text-[var(--error-strong-hover)]">
            <AppIcon name="info" size={24} color="var(--error-strong-hover)" />
          </div>
          <h3 className="text-base font-bold text-[var(--ink)] m-0">Failed to load statement</h3>
          <p className="text-xs sm:text-sm text-[var(--text-secondary)] m-0">
            {stmtError}
          </p>
          <Button
            type="button"
            variant="primary"
            onClick={fetchStatement}
            className="justify-center mx-auto mt-2"
          >
            Try again
          </Button>
        </Card>
      ) : !stmt ? (
        <Card variant="soft" className="p-8 text-center space-y-2">
          <AppIcon name="chart" size={28} color="var(--primary)" />
          <h3 className="text-base font-bold text-[var(--ink)]">
            {hasLoaded && !error && kids.length === 0
              ? "No Children Enrolled Yet"
              : "No Child Account Selected"}
          </h3>
          <p className="text-xs text-[var(--text-secondary)]">
            {hasLoaded && !error && kids.length === 0
              ? "Enroll a child account to generate monthly statements."
              : "Choose a child and statement month above to load the report."}
          </p>
        </Card>
      ) : (
        <div className="space-y-6">
          {/* Summary Metric Cards */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
            <Card variant="default" className="p-4 border border-[var(--border)]">
              <span className="text-xs text-[var(--text-secondary)] font-semibold block">Total Deposits</span>
              <div className="text-lg sm:text-xl font-bold text-[var(--success-text)] tabular-nums mt-1">
                +{fmtRM(totalIn)}
              </div>
            </Card>

            <Card variant="default" className="p-4 border border-[var(--border)]">
              <span className="text-xs text-[var(--text-secondary)] font-semibold block">Total Outflow</span>
              <div className="text-lg sm:text-xl font-bold text-[var(--ink)] tabular-nums mt-1">
                −{fmtRM(totalOut)}
              </div>
            </Card>

            <Card variant="default" className="p-4 border border-[var(--border)]">
              <span className="text-xs text-[var(--text-secondary)] font-semibold block">Net Change</span>
              <div
                className={`text-lg sm:text-xl font-bold tabular-nums mt-1 ${
                  net >= 0 ? "text-[var(--success-text)]" : "text-[var(--error-text)]"
                }`}
              >
                {net >= 0 ? "+" : "−"}{fmtRM(net)}
              </div>
            </Card>

            <Card variant="default" className="p-4 border border-[var(--border)]">
              <span className="text-xs text-[var(--text-secondary)] font-semibold block">Closing Balance</span>
              <div className="text-lg sm:text-xl font-extrabold text-[var(--primary-text)] tabular-nums mt-1">
                {fmtRM(Number(stmt.kid.balance))}
              </div>
            </Card>
          </div>

          {/* Expenses Donut Chart */}
          {totalOut > 0 && (
            <Card variant="default" className="p-5 sm:p-6 border border-[var(--border)] space-y-4">
              <h3 className="text-sm font-bold text-[var(--ink)] uppercase tracking-wider">
                Expense Category Breakdown
              </h3>
              <div className="h-52 w-full">
                <ResponsiveContainer width="100%" height="100%">
                  <PieChart>
                    <Pie
                      data={Object.entries(
                        stmtTxs
                          .filter((t) => isDebit(t.type, t.label))
                          .reduce(
                            (acc, t) => {
                              const name = TYPE_LABELS[t.type] || t.type;
                              acc[name] = (acc[name] || 0) + t.amount;
                              return acc;
                            },
                            {} as Record<string, number>,
                          ),
                      ).map(([name, value]) => ({ name, value }))}
                      cx="50%"
                      cy="50%"
                      innerRadius={55}
                      outerRadius={80}
                      paddingAngle={4}
                      dataKey="value"
                    >
                      {Object.entries(
                        stmtTxs
                          .filter((t) => isDebit(t.type, t.label))
                          .reduce(
                            (acc, t) => {
                              const name = TYPE_LABELS[t.type] || t.type;
                              acc[name] = (acc[name] || 0) + t.amount;
                              return acc;
                            },
                            {} as Record<string, number>,
                          ),
                      ).map((_, index) => (
                        <Cell key={`cell-${index}`} fill={PIE_COLORS[index % PIE_COLORS.length]} />
                      ))}
                    </Pie>
                    <RechartsTooltip formatter={(value: number) => `${formatRM(value)}`} />
                  </PieChart>
                </ResponsiveContainer>
              </div>
            </Card>
          )}

          {/* Statement printable area */}
          <div ref={stmtRef} id="statement-area" className="space-y-4">
            <Card variant="default" className="p-5 sm:p-6 border border-[var(--border)] shadow-xs space-y-5">
              {/* Statement Header */}
              <div className="flex items-start justify-between border-b border-[var(--border)] pb-4">
                <div>
                  <span className="text-xs font-bold text-[var(--primary-text)] uppercase tracking-wider block">
                    Centsibility Digital Bank
                  </span>
                  <h2 className="text-xl font-bold text-[var(--ink)] mt-0.5">
                    {stmt.kid.name}&apos;s Official Statement
                  </h2>
                  <p className="text-xs text-[var(--text-secondary)] mt-0.5">
                    Accounting Period: <strong>{format(month, "MMMM yyyy")}</strong>
                  </p>
                </div>
                <div className="text-right text-xs text-[var(--text-muted)]">
                  <span>Generated: {format(new Date(), "dd MMM yyyy")}</span>
                </div>
              </div>

              {/* Loan Fee Callout if applicable */}
              {loanFees.length > 0 && (
                <div className="p-3.5 rounded-xl bg-[var(--warning-soft)] border border-[var(--warning)]/20 text-xs space-y-1">
                  <span className="font-bold text-[var(--ink)] block">Loan Administration Fees</span>
                  {loanFees.map((f) => (
                    <div key={f.id} className="flex justify-between text-[var(--text-secondary)]">
                      <span>{f.label}</span>
                      <span className="tabular-nums font-semibold">−{fmtRM(f.amount)}</span>
                    </div>
                  ))}
                  <div className="flex justify-between pt-1 border-t border-[var(--warning)]/30 font-bold text-[var(--ink)]">
                    <span>Total Service Fees</span>
                    <span className="tabular-nums">−{fmtRM(loanFees.reduce((s, f) => s + f.amount, 0))}</span>
                  </div>
                </div>
              )}

              {/* Filter Pills */}
              <div className="flex items-center gap-1.5 overflow-x-auto no-scrollbar py-1">
                {availableTypes.map((t) => {
                  const isSelected = typeFilter === t;
                  return (
                    <button
                      key={t}
                      type="button"
                      onClick={() => setTypeFilter(t)}
                      className={`px-3 py-1.5 rounded-full text-xs font-bold shrink-0 transition-colors cursor-pointer ${
                        isSelected
                          ? "bg-[var(--primary)] text-white shadow-xs"
                          : "bg-[var(--surface-soft)] text-[var(--text-secondary)] hover:text-[var(--ink)] hover:bg-[var(--white)] border border-[var(--border)]"
                      }`}
                    >
                      {t === "ALL" ? "All Entries" : (TYPE_LABELS[t] ?? t)}
                    </button>
                  );
                })}
              </div>

              {/* Transactions List */}
              <div className="space-y-4">
                {filtered.length === 0 ? (
                  <div className="py-6 text-center text-xs text-[var(--text-muted)]">
                    No transactions recorded for this selected criteria.
                  </div>
                ) : (
                  sortedDates.map((date) => (
                    <div key={date} className="space-y-2">
                      <span className="text-[11px] font-bold text-[var(--text-muted)] uppercase tracking-wider block">
                        {format(new Date(date + "T12:00:00"), "EEEE, d MMMM yyyy")}
                      </span>
                      <div className="divide-y divide-[var(--border)] rounded-xl border border-[var(--border)] bg-white overflow-hidden">
                        {grouped[date].map((tx) => {
                          const debit = isDebit(tx.type, tx.label);
                          const runBal = balanceMap.get(tx.id);
                          return (
                            <div key={tx.id} className="p-3 flex items-center justify-between gap-3 text-xs">
                              <div>
                                <div className="flex items-center gap-2">
                                  <Badge variant={debit ? "default" : "success"}>
                                    {TYPE_LABELS[tx.type] ?? tx.type}
                                  </Badge>
                                  <strong className="text-sm font-semibold text-[var(--ink)]">
                                    {tx.label}
                                  </strong>
                                </div>
                                <span className="text-[11px] text-[var(--text-muted)] mt-0.5 block">
                                  {format(new Date(tx.created_at), "h:mm a")}
                                </span>
                              </div>

                              <div className="text-right shrink-0">
                                <span
                                  className={`text-sm font-bold tabular-nums block ${
                                    debit ? "text-[var(--ink)]" : "text-[var(--success-text)]"
                                  }`}
                                >
                                  {debit ? "−" : "+"}
                                  {fmtRM(tx.amount)}
                                </span>
                                {runBal !== undefined && (
                                  <span className="text-[10px] text-[var(--text-muted)] tabular-nums">
                                    bal {fmtRM(runBal)}
                                  </span>
                                )}
                              </div>
                            </div>
                          );
                        })}
                      </div>
                    </div>
                  ))
                )}
              </div>
            </Card>
          </div>

          {/* Export Action Buttons */}
          <div className="flex flex-wrap items-center gap-2.5">
            <Button type="button" variant="primary" onClick={handleDownloadPdf}>
              <AppIcon name="pdf" size={16} /> Print / Save PDF
            </Button>
            <Button type="button" variant="secondary" onClick={handleWhatsApp}>
              <AppIcon name="whatsapp" size={16} /> Share to WhatsApp
            </Button>
            <Button type="button" variant="secondary" onClick={handleEmail}>
              <AppIcon name="email" size={16} /> Send via Email
            </Button>
          </div>
        </div>
      )}

      {/* Loan Trust Scores */}
      <div className="space-y-3">
        <SectionTitle>Loan Reliability Scores</SectionTitle>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {kids.map((k) => (
            <Card key={k.id} variant="default" className="p-4 border border-[var(--border)] space-y-2">
              <div className="flex items-center justify-between">
                <div>
                  <strong className="text-sm font-bold text-[var(--ink)]">{k.name}</strong>
                  <span className="text-xs text-[var(--text-muted)] block">Trust Rating</span>
                </div>
                <div className="text-right">
                  <div className="text-lg font-extrabold text-[var(--ink)] tabular-nums">{k.trust_score}</div>
                  <Badge variant={k.trust_score >= 750 ? "success" : k.trust_score >= 650 ? "brand" : "warning"}>
                    {k.trust_score >= 750 ? "Excellent" : k.trust_score >= 650 ? "Good" : "Fair"}
                  </Badge>
                </div>
              </div>
              <div className="w-full bg-[var(--surface-soft)] rounded-full h-2 overflow-hidden">
                <div
                  className="bg-[var(--primary)] h-2 rounded-full transition-all duration-300"
                  style={{ width: `${Math.min(100, Math.max(0, ((k.trust_score - 300) / 600) * 100))}%` }}
                />
              </div>
            </Card>
          ))}
        </div>
      </div>

      {/* Overdue Loans Banner if any */}
      {overdue.length > 0 && (
        <div className="space-y-3">
          <SectionTitle>Overdue Repayments</SectionTitle>
          <div className="space-y-2">
            {overdue.map((l) => (
              <Card key={l.id} variant="default" className="p-4 border border-[var(--error)]/30 bg-[var(--error-soft)]/20 flex items-center justify-between gap-3">
                <div>
                  <strong className="text-sm font-bold text-[var(--ink)]">{l.kids?.name}</strong>
                  <span className="text-xs text-[var(--error-text)] block font-semibold">
                    Due Date: {l.due_date} (Overdue)
                  </span>
                </div>
                <div className="text-right">
                  <span className="text-base font-extrabold text-[var(--error-text)] tabular-nums">
                    {formatRM((Number(l.amount) - Number(l.repaid)))}
                  </span>
                </div>
              </Card>
            ))}
          </div>
        </div>
      )}

      <style>{`
        @media print {
          body > *:not(#__root) { display: none !important; }
          .fixed, nav, header { display: none !important; }
          #statement-area { display: block !important; padding: 24px; font-size: 12px; }
        }
      `}</style>
    </div>
  );
}
