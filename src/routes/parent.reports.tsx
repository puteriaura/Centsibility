import { createFileRoute } from "@tanstack/react-router";
import { useCallback, useEffect, useRef, useState } from "react";
import { useParentData } from "@/hooks/use-parent-data";
import { edgeParentGetStatement } from "@/lib/edge";
import { Skeleton } from "@/components/ui/skeleton";
import { format, startOfMonth, endOfMonth } from "date-fns";
import { toast } from "sonner";
import { PieChart, Pie, Cell, Tooltip as RechartsTooltip, ResponsiveContainer } from "recharts";
import { isDebitTransaction, TRANSACTION_TYPE_LABELS } from "@/lib/finance";
import type { StatementResult, StatementTx as Tx } from "@/types/domain";

export const Route = createFileRoute("/parent/reports")({
  head: () => ({ meta: [{ title: "Monthly Statement — Centsibility" }] }),
  component: Reports,
});



const isDebit = isDebitTransaction;
const TYPE_LABELS = TRANSACTION_TYPE_LABELS;
function fmtRM(n: number) {
  return `RM ${Math.abs(n).toFixed(2)}`;
}
function groupByDate(txs: Tx[]): Record<string, Tx[]> {
  return txs.reduce(
    (acc, tx) => {
      const d = tx.created_at.slice(0, 10);
      (acc[d] = acc[d] || []).push(tx);
      return acc;
    },
    {} as Record<string, Tx[]>,
  );
}

function Reports() {
  const { kids, loans, loading } = useParentData();
  const [kidId, setKidId] = useState<string>("");
  const [month, setMonth] = useState<Date>(startOfMonth(new Date()));
  const [typeFilter, setTypeFilter] = useState<string>("ALL");
  const [stmt, setStmt] = useState<StatementResult>(null);
  const [fetching, setFetching] = useState(false);
  const stmtRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (kids.length && !kidId) setKidId(kids[0].id);
  }, [kids, kidId]);

  const fetchStatement = useCallback(async () => {
    if (!kidId) return;
    setFetching(true);
    try {
      const res = await edgeParentGetStatement({
        kidId,
        from: format(startOfMonth(month), "yyyy-MM-dd"),
        to: format(endOfMonth(month), "yyyy-MM-dd"),
      });
      setStmt(res);
    } catch (e: unknown) {
      toast.error(e instanceof Error ? e.message : "Failed to load statement");
    } finally {
      setFetching(false);
    }
  }, [kidId, month]);

  useEffect(() => {
    fetchStatement();
  }, [fetchStatement]);

  const handleDownloadPdf = () => {
    setTimeout(() => {
      window.print();
    }, 100);
  };

  const handleWhatsApp = () => {
    if (!stmt) return;
    const text = [
      `📄 *Monthly Statement – ${stmt.kid.name}*`,
      `Period: ${format(startOfMonth(month), "d MMM")} – ${format(endOfMonth(month), "d MMM yyyy")}`,
      `Total In : ${fmtRM(totalIn)}`,
      `Total Out: ${fmtRM(totalOut)}`,
      `Net      : ${net >= 0 ? "+" : ""}${fmtRM(net)}`,
      `Balance  : ${fmtRM(stmt.kid.balance)}`,
      `\nGenerated by Centsibility`,
    ].join("\n");
    window.open(`https://wa.me/?text=${encodeURIComponent(text)}`, "_blank");
  };

  const handleEmail = () => {
    if (!stmt) return;
    const subject = `Monthly Statement – ${stmt.kid.name} – ${format(month, "MMMM yyyy")}`;
    const body = [
      `Monthly Statement for ${stmt.kid.name}`,
      `Period: ${format(startOfMonth(month), "d MMM yyyy")} – ${format(endOfMonth(month), "d MMM yyyy")}`,
      ``,
      `Total Deposits : ${fmtRM(totalIn)}`,
      `Total Debits   : ${fmtRM(totalOut)}`,
      `Net Change     : ${net >= 0 ? "+" : ""}${fmtRM(net)}`,
      `Current Balance: ${fmtRM(stmt.kid.balance)}`,
      ``,
      `Generated by Centsibility`,
    ].join("\n");
    window.open(`mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`);
  };

  if (loading) {
    return (
      <div>
        <Skeleton />
        <Skeleton />
        <Skeleton />
      </div>
    );
  }

  const stmtTxs: Tx[] = stmt?.transactions ?? [];
  const filtered = typeFilter === "ALL" ? stmtTxs : stmtTxs.filter((t) => t.type === typeFilter);
  const totalIn = stmtTxs.filter((t) => !isDebit(t.type)).reduce((s, t) => s + t.amount, 0);
  const totalOut = stmtTxs.filter((t) => isDebit(t.type)).reduce((s, t) => s + t.amount, 0);
  const net = totalIn - totalOut;

  const endBalance = stmt?.kid.balance ?? 0;
  let runningBalance = endBalance;
  const balanceMap = new Map<string, number>();
  for (let i = 0; i < stmtTxs.length; i++) {
    const tx = stmtTxs[i];
    balanceMap.set(tx.id, runningBalance);
    if (isDebit(tx.type)) runningBalance += tx.amount;
    else runningBalance -= tx.amount;
  }

  const grouped = groupByDate(filtered);
  const sortedDates = Object.keys(grouped).sort((a, b) => b.localeCompare(a));
  const availableTypes = ["ALL", ...Array.from(new Set(stmtTxs.map((t) => t.type)))];
  const loanFees = stmtTxs.filter(
    (t) => t.type === "WITHDRAWAL" && (t.label?.includes("fee") || t.label?.includes("Fee")),
  );
  const overdue = loans.filter((l) => l.status === "active" && new Date(l.due_date) < new Date());

  return (
    <>
      {/* Header + Controls */}
      <header>
        <div>
          <h1>Monthly Statement</h1>
          <p>Detailed financial oversight for your children.</p>
        </div>
        <div>
          <select
            value={kidId}
            onChange={(e) => setKidId(e.target.value)}
          >
            <option value="">Select Child</option>
            {kids.map((k) => (
              <option key={k.id} value={k.id}>
                {k.name}
              </option>
            ))}
          </select>
          <input
            type="month"
            value={format(month, "yyyy-MM")}
            onChange={(e) => {
              if (e.target.value) setMonth(startOfMonth(new Date(e.target.value + "-01")));
            }}
          />
        </div>
      </header>

      {/* Body */}
      {fetching ? (
        <div>
          {[1, 2, 3, 4].map((i) => (
            <div key={i}>[loading statement data...]</div>
          ))}
        </div>
      ) : !stmt ? (
        <section>
          <div>[icon: chart]</div>
          <h2>No child selected</h2>
          <p>Choose a child and month to view their statement.</p>
        </section>
      ) : (
        <div>
          {/* Summary Cards */}
          <div>
            <SummaryCard
              label="Total In"
              value={totalIn}
              icon="[icon: download]"
            />
            <SummaryCard
              label="Total Out"
              value={totalOut}
              icon="[icon: upload]"
            />
            <SummaryCard
              label="Net Change"
              value={net}
              icon="[icon: scales]"
            />
            <SummaryCard
              label="End Balance"
              value={Number(stmt.kid.balance)}
              icon="[icon: coins]"
            />
          </div>

          {/* Expenses Circular Graph */}
          {totalOut > 0 && (
            <section>
              <h2>Expense Breakdown</h2>
              <div style={{ height: "200px" }}>
                <ResponsiveContainer width="100%" height="100%">
                  <PieChart>
                    <Pie
                      data={Object.entries(
                        stmtTxs
                          .filter((t) => isDebit(t.type))
                          .reduce(
                            (acc, t) => {
                              const name = TYPE_LABELS[t.type] || t.type;
                              acc[name] = (acc[name] || 0) + t.amount;
                              return acc;
                            },
                            {} as Record<string, number>,
                          ),
                      ).map(([name, value]) => ({ name, value }))}
                      cx="50%"
                      cy="50%"
                      innerRadius={60}
                      outerRadius={80}
                      paddingAngle={5}
                      dataKey="value"
                    >
                      {Object.entries(
                        stmtTxs
                          .filter((t) => isDebit(t.type))
                          .reduce(
                            (acc, t) => {
                              const name = TYPE_LABELS[t.type] || t.type;
                              acc[name] = (acc[name] || 0) + t.amount;
                              return acc;
                            },
                            {} as Record<string, number>,
                          ),
                      ).map((entry, index) => {
                        const COLORS = ["#333333", "#666666", "#999999", "#cccccc", "#777777"];
                        return <Cell key={`cell-${index}`} fill={COLORS[index % COLORS.length]} />;
                      })}
                    </Pie>
                    <RechartsTooltip formatter={(value: number) => `RM ${value.toFixed(2)}`} />
                  </PieChart>
                </ResponsiveContainer>
              </div>
            </section>
          )}

          {/* Statement Container */}
          <div
            ref={stmtRef}
            id="statement-area"
          >
            {/* Statement Header */}
            <div>
              <div>
                <div>
                  <h2>Centsibility</h2>
                  <h3>{stmt.kid.name}&apos;s Statement</h3>
                  <p>
                    Period: <strong>{format(month, "MMMM yyyy")}</strong>
                  </p>
                </div>
                <div>
                  <div>Generated: {format(new Date(), "dd/MM/yyyy")}</div>
                </div>
              </div>
            </div>

            {/* Loan Fees */}
            {loanFees.length > 0 && (
              <section>
                <p>
                  [icon: warning] Loan Fee Breakdown
                </p>
                <ul>
                  {loanFees.map((f) => (
                    <li key={f.id}>
                      <span>{f.label}</span>
                      <span>−{fmtRM(f.amount)}</span>
                    </li>
                  ))}
                  <li>
                    <span><strong>Total fees:</strong></span>
                    <span>−{fmtRM(loanFees.reduce((s, f) => s + f.amount, 0))}</span>
                  </li>
                </ul>
              </section>
            )}

            {/* Type Filter */}
            <div>
              {availableTypes.map((t) => (
                <button
                  key={t}
                  onClick={() => setTypeFilter(t)}
                >
                  {typeFilter === t ? `[ ${t === "ALL" ? "All" : (TYPE_LABELS[t] ?? t)} ]` : (t === "ALL" ? "All" : (TYPE_LABELS[t] ?? t))}
                </button>
              ))}
            </div>

            {/* Transaction List */}
            <div>
              {filtered.length === 0 ? (
                <div>No transactions this period.</div>
              ) : (
                <div>
                  {sortedDates.map((date) => (
                    <div key={date}>
                      <div>
                        <strong>{format(new Date(date + "T12:00:00"), "EEEE, d MMMM yyyy")}</strong>
                      </div>
                      {grouped[date].map((tx) => {
                        const debit = isDebit(tx.type);
                        const runBal = balanceMap.get(tx.id);
                        return (
                          <div key={tx.id}>
                            <span>[{TYPE_LABELS[tx.type] ?? tx.type}]</span>
                            <div>
                              <p>{tx.label}</p>
                              <small>{format(new Date(tx.created_at), "h:mm a")}</small>
                            </div>
                            <div>
                              <p>
                                {debit ? "−" : "+"}
                                {fmtRM(tx.amount)}
                              </p>
                              {runBal !== undefined && (
                                <small>bal {fmtRM(runBal)}</small>
                              )}
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>

          {/* Actions */}
          <div>
            <button onClick={handleDownloadPdf}>
              [icon: pdf] PDF
            </button>
            <button onClick={handleWhatsApp}>
              [icon: whatsapp] WhatsApp
            </button>
            <button onClick={handleEmail}>
              [icon: email] Email
            </button>
          </div>
        </div>
      )}

      {/* Trust Overview */}
      <h2>Loan trust overview</h2>
      <div>
        {kids.map((k) => (
          <section key={k.id}>
            <div>
              <div>
                <strong>{k.name}</strong>
                <div>Trust score</div>
              </div>
              <div>
                <div>{k.trust_score}</div>
                <small>
                  {k.trust_score >= 750 ? "Excellent" : k.trust_score >= 650 ? "Good" : "Fair"}
                </small>
              </div>
            </div>
            <div>
              <progress
                value={Math.max(0, k.trust_score - 300)}
                max={600}
                style={{ width: "100%" }}
              />
            </div>
          </section>
        ))}
      </div>

      {overdue.length > 0 && (
        <>
          <h2>[icon: warning] Overdue loans</h2>
          <div>
            {overdue.map((l) => (
              <section key={l.id}>
                <div>
                  <div>
                    <strong>{l.kids?.name}</strong>
                    <div>Due {l.due_date}</div>
                  </div>
                  <div>
                    RM {(Number(l.amount) - Number(l.repaid)).toFixed(2)}
                  </div>
                </div>
              </section>
            ))}
          </div>
        </>
      )}

      <style>{`
        @media print {
          body > *:not(#__root) { display: none !important; }
          .fixed, nav, header { display: none !important; }
          #statement-area { display: block !important; padding: 24px; font-size: 12px; }
        }
      `}</style>
    </>
  );
}

function SummaryCard({
  label,
  value,
  icon,
}: {
  label: string;
  value: number;
  icon: React.ReactNode;
}) {
  return (
    <section>
      <div>
        <span>{icon}</span>
        <strong>{label}</strong>
      </div>
      <div>RM {value.toFixed(2)}</div>
    </section>
  );
}
