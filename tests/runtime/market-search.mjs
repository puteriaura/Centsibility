import assert from 'node:assert/strict';
import fs from 'node:fs';
import { sourceUrl } from './source-loader.mjs';
const { filterMarketSymbols } = await import(await sourceUrl('src/lib/market-search.ts'));
const sql = fs.readFileSync('supabase/migrations/20261005120000_market_tracker.sql', 'utf8');
const symbols = [...sql.matchAll(/\('([A-Z]+)', '([^']+)', '(stock|etf)'/g)].map(m => ({symbol:m[1],name:m[2]}));
assert.equal(symbols.length,12);
for (const query of ['AMZN','Amazon','stocks']) assert.equal(filterMarketSymbols(symbols,query).length,0);
assert.equal(filterMarketSymbols(symbols,' apple ')[0].symbol,'AAPL');
assert.equal(filterMarketSymbols(symbols,'tsla')[0].symbol,'TSLA');
console.log('Reproduced: AMZN, Amazon and stocks return zero results against the actual 12-symbol seed. Apple and TSLA match. Scope: actual filtering function and repo seed, not deployed UI.');
